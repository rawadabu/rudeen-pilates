export type Dict = (typeof DICT)['he']

/** info fills the placeholders some errors carry: {t} a clashing start time,
 *  {n} how many are booked */
export function errMsg(t: Dict, code: string | undefined, info?: { time?: string; taken?: number }): string {
  const msg = t.errors[code ?? 'unknown'] ?? t.errors.unknown
  return msg.replace('{t}', (info?.time ?? '').slice(0, 5)).replace('{n}', String(info?.taken ?? ''))
}
